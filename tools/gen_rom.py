#!/usr/bin/env python3
"""Rewrite the  BEGIN_GMB_ROM .. END_GMB_ROM  block of a design file from GMb.txt.
usage: gen_rom.py GMb.txt design.v [more.v ...]
Each file may carry a ROM block that looks like
    // ---- BEGIN_GMB_ROM
    ...
    // ---- END_GMB_ROM
The function name/width are kept: the block is regenerated as `function [13:0] gmb(input [6:0] k)`.
"""
import re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from gen_pattern import read_gmb
from ntt_model import front4_consts, front_matrix, Q


def rom_block(gmb):
    lines = ["    // ---- BEGIN_GMB_ROM (generated by tools/gen_rom.py, do not edit)",
             "    function [13:0] gmb;",
             "        input [6:0] k;",
             "        begin",
             "            case (k)"]
    for k in range(1, 128):
        lines.append("                7'd%d: gmb = 14'd%d;" % (k, gmb[k]))
    lines += ["                default: gmb = 14'd0;", "            endcase", "        end", "    endfunction",
              "    // ---- END_GMB_ROM"]
    return "\n".join(lines)


def f4_block(gmb):
    c1, c2, c3 = front4_consts(gmb)
    L = ["    // ---- BEGIN_F4_LUT (generated by tools/gen_rom.py, do not edit)",
         "    // field constants of the radix-4 front end: T_i(k,x) = c_i[k]*x mod Q"]
    def fn(name, consts, kbits):
        L.append("    function [13:0] %s;" % name)
        L.append("        input [%d:0] k;" % (kbits - 1))
        L.append("        input [3:0] x;")
        L.append("        begin")
        L.append("            case ({k, x})")
        for k, c in enumerate(consts):
            for x in range(16):
                L.append("                {%d'd%d, 4'd%d}: %s = 14'd%d;" % (kbits, k, x, name, c * x % Q))
        L.append("                default: %s = 14'd0;" % name)
        L.append("            endcase")
        L.append("        end")
        L.append("    endfunction")
    fn("t1", c1, 2)
    fn("t2", c2[0::2] if False else [c2[0], c2[2]], 1)   # +a1 for k<2, -a1 for k>=2
    fn("t3", c3, 2)
    L.append("    // ---- END_F4_LUT")
    return "\n".join(L)


def f8_block(gmb):
    """radix-8 front end tables.  For every operand i the constants C[k][i] over k take at most 4 values up to
    sign, so a table (magnitude index, x) -> |c|*x mod Q plus a sign bit (applied as Q - m, equivalent mod Q)
    replaces the full (k, x) table."""
    C = front_matrix(gmb, 3)
    L = ["    // ---- BEGIN_F8_LUT (generated by tools/gen_rom.py, do not edit)",
         "    // radix-8 front end: t_i(k,x) = C[k][i]*x mod Q  (i = 1..7), k = output block (3 bit);",
         "    // implemented as magnitude table + sign (the value Q is equivalent to 0 modulo Q)"]
    for i in range(1, 8):
        vals = [C[k][i] for k in range(8)]
        mags = sorted(set(min(v, Q - v) for v in vals))
        idx = {m: j for j, m in enumerate(mags)}
        nb = max(1, (len(mags) - 1).bit_length())
        L.append("    function [13:0] t%d;" % i)
        L.append("        input [2:0] k;")
        L.append("        input [3:0] x;")
        L.append("        reg [%d:0] sel;" % (nb - 1))
        L.append("        reg        sg;")
        L.append("        reg [13:0] m;")
        L.append("        begin")
        L.append("            case (k)")
        for k in range(8):
            L.append("                3'd%d: begin sel = %d'd%d; sg = 1'b%d; end" % (k, nb, idx[min(vals[k], Q - vals[k])], 0 if vals[k] <= Q - vals[k] else 1))
        L.append("                default: begin sel = %d'd0; sg = 1'b0; end" % nb)
        L.append("            endcase")
        L.append("            case ({sel, x})")
        for j, mg in enumerate(mags):
            for x in range(16):
                L.append("                {%d'd%d, 4'd%d}: m = 14'd%d;" % (nb, j, x, mg * x % Q))
        L.append("                default: m = 14'd0;")
        L.append("            endcase")
        L.append("            t%d = sg ? (14'd12289 - m) : m;" % i)
        L.append("        end")
        L.append("    endfunction")
    L.append("    // ---- END_F8_LUT")
    return "\n".join(L)


if __name__ == "__main__":
    gmb = read_gmb(sys.argv[1])
    blk = rom_block(gmb)
    pat = re.compile(r"[ \t]*// ---- BEGIN_GMB_ROM.*?// ---- END_GMB_ROM", re.S)
    pat4 = re.compile(r"[ \t]*// ---- BEGIN_F4_LUT.*?// ---- END_F4_LUT", re.S)
    blk4 = f4_block(gmb)
    pat8 = re.compile(r"[ \t]*// ---- BEGIN_F8_LUT.*?// ---- END_F8_LUT", re.S)
    blk8 = f8_block(gmb)
    for f in sys.argv[2:]:
        s = open(f).read()
        if not pat.search(s) and not pat4.search(s) and not pat8.search(s):
            print("no ROM block in", f); continue
        s = pat.sub(lambda m: blk, s)
        s = pat4.sub(lambda m: blk4, s)
        s = pat8.sub(lambda m: blk8, s)
        open(f, "w").write(s)
        print("updated", f)
