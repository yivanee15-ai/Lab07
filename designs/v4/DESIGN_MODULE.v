// V4 : area optimised (V3 +)
//  * CLK_1 buffer is a free running 16 x 32 ring (no hold multiplexers); the handshake reads it through a
//    16:1 tap multiplexer whose index is tracked in a 4 bit register.
//  * stages 1+2 are merged into a radix-4 front end working directly on the raw 4 bit samples: four
//    circulating 32 x 4 bit rows replace the 64 x 8 bit and 32 x 14 bit delay lines, and the two twiddle
//    multiplications become constant tables + a small adder tree.

// ------------------------------------------------------------------ CLK_1
module CLK_1_MODULE (
    input         clk,
    input         rst_n,
    input         in_valid,
    input  [31:0] in_data,
    input         sidle,
    input         sdone,
    output        sready,
    output [31:0] din
);
    // Ring of 16 words that rotates every cycle.  While in_valid is high the new word enters at the
    // tail; afterwards the head recirculates.  idx always points at the position of the next word to send.
    reg [31:0] r [0:15];
    reg [4:0]  n;              // words received
    reg [4:0]  sc;             // words handed to the handshake
    reg [3:0]  idx;
    integer i;

    always @(posedge clk) begin
        for (i = 0; i < 15; i = i + 1) r[i] <= r[i+1];
        r[15] <= in_valid ? in_data : r[0];
    end

    wire pending = (sc < n);
    wire accept  = pending & sidle;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            n   <= 5'd0;
            sc  <= 5'd0;
            idx <= 4'd0;
        end else if (sc == 5'd16) begin
            n  <= 5'd0;
            sc <= 5'd0;
        end else begin
            if (in_valid) n <= n + 5'd1;
            if (accept)   sc <= sc + 5'd1;
            if (in_valid && n == 5'd0) idx <= 4'd15;
            else if (!accept)          idx <= idx - 4'd1;   // accept: next word is one position up, ring moves one down
        end
    end

    assign sready = pending;
    assign din    = r[idx];
endmodule

// ------------------------------------------------------------------ CLK_2
module CLK_2_MODULE (
    input         clk,
    input         rst_n,
    input         dvalid,
    input  [31:0] dout,
    output        dbusy,
    input         wfull,
    output        winc,
    output [15:0] wdata
);
    // The radix-4 front end presents stream position q at tick 96+q (registered output -> seen at 97+q).
    // stages 3..6 : product/y register + output register (2 ticks); stage 7 : 1 tick, feeds the FIFO.
    localparam D3 = 97;
    localparam D4 = D3 + 16 + 2;
    localparam D5 = D4 + 8  + 2;
    localparam D6 = D5 + 4  + 2;
    localparam D7 = D6 + 2  + 2;
    localparam D8 = D7 + 1  + 1;      // first output position is presented on y7 here
    localparam GEND = D8 + 127;

    reg  [8:0] g;                // global tick counter
    reg  [4:0] wi;               // words received from the handshake

    wire [4:0] wi_nxt = wi + {4'd0, dvalid};
    wire       in_ph  = (g[8:7] == 2'b00);
    wire       have   = (wi_nxt > {1'b0, g[6:3]});
    wire       adv    = (~in_ph | have) & ~wfull;

    assign dbusy = in_ph & (wi > {1'b0, g[6:3]});

    wire       out_win = (g >= D8) & (g <= GEND);
    assign winc  = out_win & ~wfull;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            g  <= 9'd0;
            wi <= 5'd0;
        end else begin
            wi <= wi_nxt;
            if (adv) begin
                if (g == GEND) begin
                    g  <= 9'd0;
                    wi <= 5'd0;
                end else g <= g + 9'd1;
            end
        end
    end

    wire [3:0]  xin = dout >> {g[2:0], 2'b00};
    wire [13:0] y2, y3, y4, y5, y6, y7;

    FRONT4 u_f4 (.clk(clk), .adv(adv), .g(g), .x_in(xin), .y_out(y2));
    SDF_STAGE #(.S(3), .DOFF(D3)) u_s3 (.clk(clk), .adv(adv), .g(g), .x_in(y2), .y_out(y3));
    SDF_STAGE #(.S(4), .DOFF(D4)) u_s4 (.clk(clk), .adv(adv), .g(g), .x_in(y3), .y_out(y4));
    SDF_STAGE #(.S(5), .DOFF(D5)) u_s5 (.clk(clk), .adv(adv), .g(g), .x_in(y4), .y_out(y5));
    SDF_STAGE #(.S(6), .DOFF(D6)) u_s6 (.clk(clk), .adv(adv), .g(g), .x_in(y5), .y_out(y6));
    SDF_STAGE #(.S(7), .DOFF(D7), .OREG(0)) u_s7 (.clk(clk), .adv(adv), .g(g), .x_in(y6), .y_out(y7));

    assign wdata = {2'b00, y7};
endmodule

