module CLK_3_MODULE (
    input         clk,
    input         rst_n,
    input         rempty,
    input  [15:0] rdata,
    output        rinc,
    output        out_valid,
    output [15:0] out_data
);
    reg v1, v2;
    assign rinc = ~rempty;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            v1 <= 1'b0;
            v2 <= 1'b0;
        end else begin
            v1 <= rinc;
            v2 <= v1;
        end
    end
    assign out_valid = v2;
    assign out_data  = v2 ? rdata : 16'd0;
endmodule
