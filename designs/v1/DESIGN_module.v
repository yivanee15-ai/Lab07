// V1 : straightforward reference design.
//  CLK_1 : buffer the 16 input words, then send them one by one through the handshake.
//  CLK_2 : collect 128 coefficients, run the 448 butterflies one per cycle (behavioural
//          Montgomery multiplier exactly as in the spec), then stream results into the FIFO.
//  CLK_3 : pop the FIFO and align out_valid / out_data.

// ------------------------------------------------------------------ CLK_1
module CLK_1_MODULE (
    input         clk,
    input         rst_n,
    input         in_valid,
    input  [31:0] in_data,
    input         out_idle,                 // sidle of the handshake
    output        out_valid,                // sready
    output [31:0] out_data,                 // din
    input         flag_handshake_to_clk1,   // synchronised acknowledge (sdone)
    output        flag_clk1_to_handshake
);
    wire        sidle = out_idle;
    wire        sdone = flag_handshake_to_clk1;
    wire        sready;
    wire [31:0] din;
    assign out_valid = sready;
    assign out_data  = din;
    assign flag_clk1_to_handshake = 1'b0;
    reg [31:0] buffer [0:15];
    reg [3:0]  wcnt;
    reg [4:0]  scnt;       // words sent
    reg        full;       // all 16 words received
    reg        sdone_q;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            wcnt <= 4'd0;
            full <= 1'b0;
        end else if (in_valid) begin
            wcnt <= wcnt + 4'd1;
            if (wcnt == 4'd15) full <= 1'b1;
        end else if (scnt == 5'd16) begin
            full <= 1'b0;
        end
    end
    always @(posedge clk) if (in_valid) buffer[wcnt] <= in_data;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            scnt    <= 5'd0;
            sdone_q <= 1'b0;
        end else begin
            sdone_q <= sdone;
            if (sdone & ~sdone_q) scnt <= scnt + 5'd1;
            else if (scnt == 5'd16 && !full) scnt <= 5'd0;
        end
    end

    assign sready = full & sidle & (scnt != 5'd16);
    wire [31:0] din_nxt;
    assign din_nxt = buffer[scnt[3:0]];
    // din is the next word while the handshake is idle and a registered copy of it as soon as a transfer is
    // running, so din cannot change between the request and the end of the 4-phase handshake whatever the
    // input does (Jasper data-stability check).  No extra latency: the first idle cycle already shows the new word.
    reg  [31:0] dr;
    always @(posedge clk) dr <= din;
    assign din = sidle ? din_nxt : dr;

endmodule

