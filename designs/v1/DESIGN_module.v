    function [13:0] modq_mul;
        input [13:0] a;
        input [13:0] b;
        reg [27:0] x;
        reg [15:0] y;
        reg [30:0] t;
        reg [14:0] z;
        begin
            x = a * b;
            y = (x[15:0] * 16'd12287);
            t = x + y * 15'd12289;
            z = t[30:16];
            modq_mul = (z >= Q) ? z - Q : z;
        end
    endfunction

    localparam S_COLLECT = 2'd0, S_CALC = 2'd1, S_OUT = 2'd2;
    reg [1:0]  state;
    reg [13:0] x [0:127];
    reg [4:0]  wrcnt;          // words received
    reg [2:0]  stage;          // 0..6
    reg [6:0]  idx;            // butterfly index inside stage (0..63)
    reg [7:0]  ocnt;

    // butterfly addressing:  ht = 64>>stage; block i = idx / ht ; j = i*2*ht + idx % ht
    wire [6:0] ht   = 7'd64 >> stage;
    wire [6:0] pos  = idx & (ht - 7'd1);
    wire [6:0] blk  = idx >> (6 - stage);
    wire [6:0] j    = (blk << (7 - stage)) + pos;
    wire [6:0] jh   = j + ht;
    wire [6:0] s_idx = (7'd1 << stage) + blk;
    wire [13:0] u_v = x[j];
    wire [13:0] v_v = modq_mul(x[jh], gmb(s_idx));
    wire [14:0] sum_raw  = {1'b0, u_v} + {1'b0, v_v};
    wire [13:0] sum_mod  = (sum_raw >= Q) ? sum_raw - Q : sum_raw[13:0];
    wire [14:0] dif_raw  = {1'b0, u_v} - {1'b0, v_v};
    wire [13:0] dif_mod  = dif_raw[14] ? dif_raw[13:0] + Q : dif_raw[13:0];

    assign dbusy = (state != S_COLLECT);
    assign winc  = (state == S_OUT) & ~wfull;
    assign wdata = {2'b00, x[ocnt[6:0]]};

    integer ii;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            state <= S_COLLECT;
            wrcnt <= 5'd0;
            stage <= 3'd0;
            idx   <= 7'd0;
            ocnt  <= 8'd0;
        end else begin
            case (state)
                S_COLLECT: if (dvalid) begin
                    for (ii = 0; ii < 8; ii = ii + 1)
                        x[{wrcnt[3:0], 3'b000} + ii] <= {10'd0, dout[4*ii +: 4]};
                    wrcnt <= wrcnt + 5'd1;
                    if (wrcnt == 5'd15) begin
                        state <= S_CALC; stage <= 3'd0; idx <= 7'd0;
                    end
                end
                S_CALC: begin
                    x[j]  <= sum_mod;
                    x[jh] <= dif_mod;
                    if (idx == 7'd63) begin
                        idx <= 7'd0;
                        if (stage == 3'd6) begin
                            state <= S_OUT; ocnt <= 8'd0;
                        end else stage <= stage + 3'd1;
                    end else idx <= idx + 7'd1;
                end
                S_OUT: if (!wfull) begin
                    ocnt <= ocnt + 8'd1;
                    if (ocnt == 8'd127) begin
                        state <= S_COLLECT; wrcnt <= 5'd0;
                    end
                end
            endcase
        end
    end
endmodule

